// Builds SQL that loads the demo data (src/lib/seed.ts) into an empty live database.
//
//   npx tsx scripts/seed-sql.ts --owner you@example.com > seed.sql
//
// The demo owner gets the --owner email, so signing in with it makes that account the theatre owner.
// Everyone else keeps their @example.com address until the owner edits them in People & access.

import * as R from '../src/lib/remote/rows';
import { DEFAULT_HOUSE } from '../src/lib/seating';
import { buildSeed, DEFAULT_SETTINGS, OWNER_ID, VENUE } from '../src/lib/seed';

export function seedSql(ownerEmail: string, now: Date = new Date()): string {
  const seed = buildSeed(now);

  // keeps list order (people, channels…) stable when the app sorts by created_at
  let tick = now.getTime() - 3600_000;
  const stamp = () => new Date((tick += 1000)).toISOString();

  function insert(table: string, rows: object[]): string {
    if (!rows.length) return '';
    const json = JSON.stringify(rows).replace(/'/g, "''");
    return `insert into public.${table} select * from jsonb_populate_recordset(null::public.${table}, '${json}'::jsonb);\n`;
  }

  const people = seed.users.map((u) => ({
    ...R.fromUser(u),
    email: u.id === OWNER_ID ? ownerEmail : u.email,
    phone: u.phone ?? null,
    auth_user_id: null,
    created_at: stamp(),
  }));

  const bookings = seed.bookings.map((b) => R.fromBooking(b));
  const payments = seed.bookings.flatMap((b) =>
    b.payments.map((p) => ({ id: p.id, booking_id: b.id, amount: p.amount, kind: p.kind, method: p.method, reference: p.reference ?? null, at: p.at })),
  );

  const productions = seed.productions.map((p) => ({ ...R.fromProduction(p), created_at: stamp() }));
  const memberships = seed.productions.flatMap((p) => p.members.map((m) => ({ ...R.fromMembership(p.id, m), created_at: stamp() })));
  const schedule = seed.schedule.map((s) => R.fromScheduleItem(s));
  const rsvps = seed.schedule.flatMap((s) => Object.entries(s.rsvps).map(([person_id, answer]) => ({ item_id: s.id, person_id, answer })));
  const conflicts = seed.conflicts.map(R.fromConflict);
  const channels = seed.channels.map((c) => ({ ...R.fromChannel(c), created_at: stamp() }));
  const messages = seed.messages.map((m) => ({ id: m.id, channel_id: m.channelId, person_id: m.userId, body: m.text, at: m.at }));

  const performances = seed.performances.map(({ seats: _seats, ...p }) => R.fromPerformance(p));
  const claims = seed.performances.flatMap((p) =>
    Object.entries(p.seats).map(([seat_id, c]) => ({
      performance_id: p.id,
      seat_id,
      status: c.status,
      holder_id: c.holderId ?? null,
      hold_expires_at: c.holdExpiresAt ?? null,
      order_id: c.orderId ?? null,
      note: c.note ?? null,
    })),
  );
  const orders = seed.orders.map((o) => ({
    id: o.id,
    performance_id: o.performanceId,
    seat_ids: o.seatIds,
    buyer_id: o.buyerUserId ?? null,
    buyer_name: o.buyerName,
    buyer_email: o.buyerEmail,
    subtotal: o.subtotal,
    fees: o.fees,
    total: o.total,
    method: o.method,
    refunded: !!o.refunded,
    at: o.at,
  }));
  const tickets = seed.tickets.map((t) => ({
    id: t.id,
    order_id: t.orderId,
    performance_id: t.performanceId,
    seat_id: t.seatId,
    code: t.code,
    price: t.price,
    checked_in_at: t.checkedInAt ?? null,
    void: !!t.void,
  }));

  const config = [{ id: 1, venue: VENUE, settings: DEFAULT_SETTINGS, house: DEFAULT_HOUSE, setup: {}, updated_at: now.toISOString() }];

  return (
    [
      '-- Demo data for The Dream Theatre, generated by scripts/seed-sql.ts',
      'begin;',
      insert('venue_config', config),
      insert('people', people),
      insert('bookings', bookings),
      insert('payments', payments),
      insert('productions', productions),
      insert('memberships', memberships),
      insert('schedule_items', schedule),
      insert('rsvps', rsvps),
      insert('member_conflicts', conflicts),
      insert('channels', channels),
      insert('messages', messages),
      insert('performances', performances),
      insert('seat_claims', claims),
      insert('orders', orders),
      insert('tickets', tickets),
      'commit;',
      '',
    ].join('\n')
  );
}

// npx tsx scripts/seed-sql.ts --owner you@example.com
if (process.argv[1]?.endsWith('seed-sql.ts')) {
  const i = process.argv.indexOf('--owner');
  const owner = i > 0 ? process.argv[i + 1] : undefined;
  if (!owner || !/^\S+@\S+\.\S+$/.test(owner)) {
    console.error('Usage: npx tsx scripts/seed-sql.ts --owner you@example.com');
    process.exit(1);
  }
  process.stdout.write(seedSql(owner));
}
